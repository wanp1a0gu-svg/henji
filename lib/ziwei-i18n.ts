/** 中文宫名 → 各语言的宫位索引（用于把引擎返回的 name 映射成序号） */
const PALACE_INDEX: Record<string, number> = {
  命宫: 0, 兄弟宫: 1, 夫妻宫: 2, 子女宫: 3, 财帛宫: 4, 疾厄宫: 5,
  迁移宫: 6, 交友宫: 7, 仆役宫: 7, 官禄宫: 8, 田宅宫: 9, 福德宫: 10, 父母宫: 11,
};

export function palaceLabel(locale: Locale, name: string): string {
  const t = getZiweiMessages(locale);
  const idx = PALACE_INDEX[name];
  if (idx === undefined) return name;
  return t.palaces[idx];
}

